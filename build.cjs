"use strict";
// Rebuild the self-contained offline entry without npm packages or network access.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const directory = __dirname;
let html = fs.readFileSync(path.join(directory, "index.html"), "utf8");
html = html.replace('<link rel="stylesheet" href="styles.css">', () =>
  `<style>\n${fs.readFileSync(path.join(directory, "styles.css"), "utf8")}\n</style>`);
html = html.replace(/<script src="([a-z]+\.js)"><\/script>/g, (_, filename) =>
  `<script>\n${fs.readFileSync(path.join(directory, filename), "utf8").replace(/<\/script/gi, "<\\/script")}\n</script>`);
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build.cjs. Edit index.html, styles.css and the JS sources, not this file. -->");
const target = path.join(directory, "offline.html");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== html)
  fs.writeFileSync(target, html, "utf8");
console.log(`Offline entry: ${target} (${Buffer.byteLength(html)} bytes)`);
const context = vm.createContext({});
for (const filename of ["core.js", "geometry.js", "relief.js", "pixel-art.js", "pixel-guide.js", "artwork.js"])
  vm.runInContext(fs.readFileSync(path.join(directory, filename), "utf8"), context, { filename });
const Lab = context.DualGridLab, map = Lab.continuousMap();
const states = new Set(), pending = new Set();
for (let y = 0; y <= map.height; y++)
  for (let x = 0; x <= map.width; x++) {
    if (Lab.get(map, x, y)) pending.add(`${x},${y}`);
    if (x < map.width && y < map.height) states.add(Lab.mask(map, x, y));
  }
// Connected saddle contours join occupied diagonal samples inside the sheet, never by wrapping.
let landGroups = 0;
while (pending.size) {
  landGroups++;
  const first = pending.values().next().value, stack = [first];
  pending.delete(first);
  while (stack.length) {
    const [x, y] = stack.pop().split(",").map(Number);
    for (let dy = -1; dy <= 1; dy++)
      for (let dx = -1; dx <= 1; dx++) {
        const key = `${x + dx},${y + dy}`;
        if (pending.delete(key)) stack.push(key);
      }
  }
}
if (states.size !== 16 || landGroups !== 1)
  throw new Error("The default drawing sheet must contain all 16 states and one non-wrapped land group.");
console.log(`Static drawing contract: ${states.size} states / ${landGroups} non-wrapped land group`);
const templates = path.join(directory, "templates");
fs.mkdirSync(templates, { recursive: true });
const examples = [["ortho", 128], ["iso", 128], ["pseudo", 128], ["ortho", 4], ["ortho", 8]];
for (const [mode, size] of examples) {
  const svg = context.DualGridLab.guideSvg({ size, view: mode === "iso" ? "iso" : "ortho",
    style: mode === "pseudo" ? "pseudo" : "flat", grid: true, filter: "nearest" });
  const output = path.join(templates, `continuous-${mode}-${size}.svg`);
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== svg)
    fs.writeFileSync(output, svg, "utf8");
  console.log(`Layered template: ${output}`);
}
